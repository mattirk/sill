/// Start at a random combination, then search every base before using a suffix.
pub fn unused_name(used: &HashSet<String>) -> String {
    use rand::RngExt;
    let start = rand::rng().random_range(0..ADJECTIVES.len() * NOUNS.len());
    unused_from(used, start)
}

pub(crate) fn base_name(index: usize) -> String {
    format!(
        "{}-{}",
        ADJECTIVES[index / NOUNS.len()],
        NOUNS[index % NOUNS.len()]
    )
}

fn unused_from(used: &HashSet<String>, start: usize) -> String {
    let total = ADJECTIVES.len() * NOUNS.len();
    for offset in 0..total {
        let name = base_name((start + offset) % total);
        if !used.contains(&name) {
            return name;
        }
    }
    let base = base_name(start);
    // Every base is occupied. Skip suffixes already used or assigned by a person.
    for suffix in 2u64.. {
        let name = format!("{base}-{suffix}");
        if !used.contains(&name) {
            return name;
        }
    }
    unreachable!("a stored name set cannot exhaust u64 suffixes")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vocabulary_is_complete_distinct_and_simple() {
        assert_eq!(ADJECTIVES.len(), 200);
        assert_eq!(NOUNS.len(), 300);
        for words in [ADJECTIVES, NOUNS] {
            assert_eq!(words.iter().collect::<HashSet<_>>().len(), words.len());
            assert!(
                words
                    .iter()
                    .all(|w| !w.is_empty() && w.bytes().all(|c| c.is_ascii_lowercase()))
            );
        }
    }

    #[test]
    fn searches_all_bases_before_suffixing_and_skips_used_suffixes() {
        let mut used: HashSet<_> = (0..60_000).map(base_name).collect();
        let last = base_name(59_999);
        used.remove(&last);
        assert_eq!(unused_from(&used, 0), last);
        used.insert(last);
        used.insert(format!("{}-2", base_name(0)));
        assert_eq!(unused_from(&used, 0), format!("{}-3", base_name(0)));
    }

    #[test]
    fn collision_search_wraps_and_freed_names_can_be_reused() {
        let mut used = HashSet::from([base_name(59_999), base_name(0)]);
        assert_eq!(unused_from(&used, 59_999), base_name(1));
        used.remove(&base_name(0));
        assert_eq!(unused_from(&used, 59_999), base_name(0));
    }
}
